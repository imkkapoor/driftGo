-- Transfer domain schema (for sqlc compilation)
-- References users table from user domain

CREATE TYPE user_status AS ENUM ('active', 'pending');

CREATE TABLE IF NOT EXISTS users (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    stytch_user_id TEXT NOT NULL UNIQUE,
    first_name TEXT,
    last_name TEXT,
    email TEXT NOT NULL,
    status user_status NOT NULL DEFAULT 'active',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS link_item (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    access_token TEXT NOT NULL,
    item_id TEXT NOT NULL,
    institution_id TEXT,
    institution_name TEXT,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS link_account (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    account_id TEXT NOT NULL UNIQUE,
    item_id BIGINT NOT NULL REFERENCES link_item(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name TEXT,
    official_name TEXT,
    mask TEXT,
    subtype TEXT,
    type TEXT,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TYPE transfer_status AS ENUM (
    'pending',
    'debit_authorized',
    'debit_pending',
    'debit_settled',
    'credit_authorized',
    'credit_pending',
    'completed',
    'failed',
    'returned',
    'cancelled'
);

CREATE TABLE IF NOT EXISTS transfer (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    sender_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    receiver_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    sender_account_id TEXT NOT NULL,
    receiver_account_id TEXT NOT NULL,
    amount NUMERIC(12,2) NOT NULL,
    currency TEXT NOT NULL DEFAULT 'USD',
    status transfer_status NOT NULL DEFAULT 'pending',
    description TEXT,
    idempotency_key TEXT NOT NULL UNIQUE,
    debit_authorization_id TEXT,
    credit_authorization_id TEXT,
    debit_transfer_id TEXT,
    credit_transfer_id TEXT,
    failure_reason TEXT,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ,
    CONSTRAINT chk_no_self_transfer CHECK (sender_user_id != receiver_user_id)
);
