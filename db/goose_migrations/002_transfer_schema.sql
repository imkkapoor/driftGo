-- Transfer domain schema
CREATE TYPE transfer_status AS ENUM (
    'pending',
    'debit_authorized',
    'debit_pending',
    'debit_settled',
    'credit_authorized',
    'credit_pending',
    'completed',
    'failed',
    'returned',
    'cancelled'
);

CREATE TABLE IF NOT EXISTS transfer (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    sender_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    receiver_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    sender_account_id TEXT NOT NULL,   -- encrypted Plaid account ID
    receiver_account_id TEXT NOT NULL, -- encrypted Plaid account ID
    amount NUMERIC(12,2) NOT NULL,
    currency TEXT NOT NULL DEFAULT 'USD',
    status transfer_status NOT NULL DEFAULT 'pending',
    description TEXT,
    idempotency_key TEXT NOT NULL UNIQUE,
    debit_authorization_id TEXT,
    credit_authorization_id TEXT,
    debit_transfer_id TEXT,
    credit_transfer_id TEXT,
    failure_reason TEXT,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ,
    CONSTRAINT chk_no_self_transfer CHECK (sender_user_id != receiver_user_id)
);

CREATE INDEX IF NOT EXISTS idx_transfer_sender_user_id ON transfer(sender_user_id);
CREATE INDEX IF NOT EXISTS idx_transfer_receiver_user_id ON transfer(receiver_user_id);
CREATE INDEX IF NOT EXISTS idx_transfer_status ON transfer(status);
CREATE INDEX IF NOT EXISTS idx_transfer_debit_transfer_id ON transfer(debit_transfer_id);
CREATE INDEX IF NOT EXISTS idx_transfer_credit_transfer_id ON transfer(credit_transfer_id);
CREATE INDEX IF NOT EXISTS idx_transfer_idempotency_key ON transfer(idempotency_key);

